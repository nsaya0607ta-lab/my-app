/* チャッピーAIの並べ替え意見（1人用でAI同士の順番を決めるとき用）。
   AIは自分の数字を知っているので、AI同士の相対順は正しく並べられるが、
   それをそのまま使うとプレイヤーが「AIの並び＝正解」と学習してしまう。
   そのため、難易度に応じた確率で隣同士を入れ替えたゆらぎを入れる。 */
export function vgAiSuggestOrder(entries, clarity){
  const c = Math.max(0, Math.min(1, clarity === undefined ? 0.6 : clarity));
  const list = entries.slice().sort((a, b) => a.number - b.number);
  for(let i = 0; i < list.length - 1; i++){
    if(Math.random() > c){
      const t = list[i]; list[i] = list[i + 1]; list[i + 1] = t;
      i++; // 同じ要素を続けて入れ替えない
    }
  }
  return list;
}
